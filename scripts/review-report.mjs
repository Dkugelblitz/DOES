#!/usr/bin/env node
// Writes docs/content-review.md: every topic's level flags, for human review.
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadContent, validate } from "./validate-seed.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const c = loadContent(); const { stats, errors } = validate(c);
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
const L = ["", "DE", "PDE", "DA"];
const lines = [
  "# Content review: level flags", "",
  "Generated by `npm run seed:report`. Review the **min_level** and **Pareto** columns; edit `scripts/legacy/flags.mjs` and rebuild.", "",
  "- **min_level**: lowest level whose roadmap shows the topic (DE = Data Engineer, PDE = Principal, DA = Architect).",
  "- **Pareto**: levels for which the topic is in the core ~20%.",
  "- **Basis**: `academy` = min_level copied from the prototype row named; `proposed` = no prototype row, Claude's suggestion. Pareto was rebalanced for all rows.",
  "- ➕ = topic added from the academy prototype (not in your dashboard list). Databricks has no additions.", "",
  "## Summary", "",
  "| Level | Roadmap topics | Pareto topics | Pareto share | Cards | Designs | Sprint items |", "|---|---|---|---|---|---|---|",
  ...stats.perLevel.map(p => `| ${p.level} ${L[p.level]} | ${p.visible} | ${p.pareto} | ${p.share}% | ${p.cards} | ${p.designs} | ${p.sprint_items} |`), "",
  `${stats.topics} topics, ${stats.subtopics} subtopics, ${stats.proposed_flags} proposed flags, ${stats.added_topics} added topics.`, "",
];
for (const d of c.domains.domains) {
  lines.push(`## ${d.icon} ${d.name}`, "", "| Topic | Module | min_level | Pareto | Basis |", "|---|---|---|---|---|");
  for (const t of c.topics.filter(t => t.domain === d.slug)) {
    const mod = d.modules.find(m => m.slug === t.module).name;
    lines.push(`| ${t.provenance.added_from_academy ? "➕ " : ""}${t.name.replace(/\|/g, "\\|")} | ${mod} | ${t.min_level} ${L[t.min_level]} | ${t.pareto_levels.map(l => L[l]).join(", ") || "–"} | ${t.provenance.basis}${t.provenance.basis === "academy" ? `: ${t.provenance.note}` : ""} |`);
  }
  lines.push("");
}
mkdirSync(join(ROOT, "docs"), { recursive: true });
writeFileSync(join(ROOT, "docs/content-review.md"), lines.join("\n"));
console.log("Wrote docs/content-review.md");
