#!/usr/bin/env node
// Builds content/*.yaml from the verbatim legacy data in scripts/legacy/.
// The YAML files are the initial seed. After seeding, the database (edited via
// the admin console, with version history) is the live source of truth.
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";
import { D, DASHBOARD_DEFAULTS, RESOURCE_KINDS } from "./legacy/dashboard.mjs";
import { PLAN, CARDS, DES, HR, HR_DISCLAIMER, FRAMEWORK, SPRINT_INTRO } from "./legacy/sprint.mjs";
import { R, RD, ICONS, TITLES, BADGES, CH, BYE } from "./legacy/academy.mjs";
import { FLAGS, ADDITIONS } from "./legacy/flags.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "content");
export const slug = s => s.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const digits = p => [...p].map(Number).sort();
const HEADER = "# Generated by scripts/build-seed.mjs from scripts/legacy/*. Initial seed only:\n# after seeding, edit content in the admin console (versioned in the database).\n";
const write = (rel, data) => {
  const f = join(OUT, rel); mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, HEADER + YAML.stringify(data, { lineWidth: 0 }));
};

rmSync(OUT, { recursive: true, force: true });

// ---------- levels ----------
const LEVEL_KEYS = ["data_engineer", "principal_data_engineer", "data_architect"];
write("levels.yaml", { levels: R.map((name, i) => ({ level: i + 1, key: LEVEL_KEYS[i], name, icon: ICONS[i], description: RD[i] })) });

// ---------- domains, modules, topics ----------
const domains = []; const topicIndex = new Map(); // "Domain|Name" -> id
const unused = new Set(Object.keys(FLAGS));
Object.entries(D).forEach(([dName, dv], di) => {
  const dSlug = slug(dName);
  const modules = Object.keys(dv.m).map((m, mi) => ({ slug: slug(m), name: m, order: mi + 1 }));
  const topics = [];
  Object.entries(dv.m).forEach(([mName, list]) => list.forEach(raw => {
    const [name, subs] = raw.split("|"); const key = `${dName}|${name}`;
    const f = FLAGS[key]; if (!f) throw new Error(`No level flags for ${key}`); unused.delete(key);
    topics.push({ name, subs: subs ? subs.split(";") : [], module: slug(mName), f, added: false });
  }));
  ADDITIONS.filter(a => a.domain === dName).forEach(a => {
    if (!modules.find(m => m.slug === slug(a.module))) modules.push({ slug: slug(a.module), name: a.module, order: modules.length + 1 });
    topics.push({ name: a.name, subs: a.subtopics, module: slug(a.module), f: a.flags, added: true });
  });
  const out = topics.map((t, i) => {
    const id = `${dSlug}/${slug(t.name)}`; topicIndex.set(`${dName}|${t.name}`, id);
    const [min, par, basis] = t.f;
    return {
      id, slug: slug(t.name), name: t.name, module: t.module, order: i + 1,
      min_level: min, pareto_levels: digits(par),
      subtopics: t.subs.map((s, si) => ({ slug: slug(s) || `sub-${si + 1}`, name: s })),
      provenance: { basis: basis.startsWith("a:") ? "academy" : "proposed", note: basis.replace(/^a:/, ""), ...(t.added ? { added_from_academy: true } : {}) },
    };
  });
  domains.push({ slug: dSlug, name: dName, icon: dv.i, order: di + 1, modules });
  write(`topics/${dSlug}.yaml`, { domain: dSlug, topics: out });
});
if (unused.size) throw new Error("Flags for unknown topics: " + [...unused].join(", "));
write("domains.yaml", { domains });

const T = (domain, name) => { const id = topicIndex.get(`${domain}|${name}`); if (!id) throw new Error(`Unknown topic ${domain}|${name}`); return id; };

// ---------- flip cards (each linked to a topic; level inherited) ----------
const CARD_TOPIC = [
  T("Databricks","Transaction Log (_delta_log)"), T("Databricks","OPTIMIZE"), T("Databricks","Liquid Clustering"), T("Databricks","VACUUM"),
  T("Databricks","MERGE (SCD1/SCD2, CDC)"), T("Databricks","MERGE (SCD1/SCD2, CDC)"), T("Databricks","Catalogs"), T("Databricks","Row-Level Security"),
  T("Databricks","Auto Loader"), T("Databricks","Exactly-Once Processing"), T("Databricks","Lakeflow / Declarative Pipelines"), T("Databricks","Jobs"),
  T("PySpark","Data skew handling"), T("PySpark","Joins & broadcast"), T("PySpark","Shuffle & partitioning"), T("PySpark","UDFs & pandas UDFs"),
  T("PySpark","Spark UI debugging"), T("PySpark","Structured Streaming"),
  T("AWS","S3"), T("AWS","Glue"), T("AWS","Kinesis / MSK"), T("AWS","IAM"), T("AWS","DR & multi-region"),
  T("Gen AI","RAG architecture"), T("Gen AI","Chunking & retrieval strategies"), T("Gen AI","Evaluation & guardrails"), T("Gen AI","Fine-tuning (LoRA / PEFT)"),
  T("Gen AI","Agents & tool use"), T("Gen AI","Cost & latency optimization"),
  T("Python","Concurrency (GIL, threads, asyncio)"), T("Python","Data structures & complexity"), T("Python","Generators & iterators"),
  T("SQL Coding","Deduplication"), T("SQL Coding","Gaps & islands"), T("SQL Coding","Sessionization"), T("SQL Coding","Joins (all types, self joins)"), T("SQL Coding","Running totals & moving averages"),
];
if (CARD_TOPIC.length !== CARDS.length) throw new Error("card/topic mapping length mismatch");
const cardSeen = {};
write("cards.yaml", { cards: CARDS.map(([deck, q, a], i) => {
  const base = `${slug(deck)}-${slug(q).slice(0, 40).replace(/-+$/, "")}`; cardSeen[base] = (cardSeen[base] || 0) + 1;
  return { id: cardSeen[base] > 1 ? `${base}-${cardSeen[base]}` : base, deck, question: q, answer: a, topic: CARD_TOPIC[i], min_level: "inherit", order: i + 1 };
}) });

// ---------- system designs ----------
const DESIGN_META = [
  { min_level: 1, topics: [T("Architecture","Medallion lakehouse")] },
  { min_level: 2, topics: [T("Architecture","CDC pipeline design"), T("Databricks","CDC")] },
  { min_level: 3, topics: [T("Architecture","Real-time analytics platform")] },
  { min_level: 3, topics: [T("Architecture","RAG platform design"), T("Gen AI","RAG architecture")] },
  { min_level: 3, topics: [T("Architecture","Multi-tenant governed platform")] },
  { min_level: 3, topics: [T("HackerRank AI-Era","AI interviewer / resume deep dive")] },
];
write("designs.yaml", {
  answer_framework: { min_level: 1, total_minutes: FRAMEWORK.reduce((a, [, m]) => a + m, 0), steps: FRAMEWORK.map(([step, minutes]) => ({ step, minutes })) },
  designs: DES.map(([title, points], i) => ({ id: slug(title.replace(/\(.*\)/, "")), title, ...DESIGN_META[i], points, order: i + 1 })),
});

// ---------- 2-day sprint ----------
// Block min_level = lowest level that should see it. Items may raise their own level.
const BLOCK_META = {
  "Delta Lake essentials": { min_level: 1, topics: [T("Databricks","Transaction Log (_delta_log)"), T("Databricks","OPTIMIZE"), T("Databricks","VACUUM"), T("Databricks","MERGE (SCD1/SCD2, CDC)")], item_levels: { 4: 2 } },
  "Unity Catalog & governance": { min_level: 1, topics: [T("Databricks","Catalogs"), T("Databricks","Permissions")], item_levels: { 2: 2 } },
  "Ingestion & streaming": { min_level: 1, topics: [T("Databricks","Auto Loader"), T("Databricks","Streaming")], item_levels: { 2: 2, 3: 2 } },
  "PySpark performance": { min_level: 1, topics: [T("PySpark","Shuffle & partitioning"), T("PySpark","Joins & broadcast")], item_levels: { 3: 2 } },
  "SQL coding drills": { min_level: 1, topics: [T("SQL Coding","Deduplication"), T("SQL Coding","Window functions")], item_levels: { 2: 2, 4: 2 } },
  "Design drills 1–2 (talk out loud)": { min_level: 1, topics: [T("Architecture","Medallion lakehouse")], item_levels: { 1: 2 } },
  "HackerRank AI-assisted format": { min_level: 1, topics: [T("HackerRank AI-Era","AI-assisted IDE workflow")] },
  "Python coding": { min_level: 1, topics: [T("Python","Hash maps & sets")], item_levels: { 1: 2 } },
  "AWS data stack": { min_level: 1, topics: [T("AWS","S3"), T("AWS","Glue")], item_levels: { 2: 2, 3: 2, 4: 3 } },
  "Gen AI": { min_level: 2, topics: [T("Gen AI","RAG architecture")], item_levels: { 1: 3, 2: 3 } },
  "Design drills 3–5": { min_level: 3, topics: [T("Architecture","Real-time analytics platform"), T("Architecture","RAG platform design"), T("Architecture","Multi-tenant governed platform")] },
  "Behavioral + resume deep dive": { min_level: 1, topics: [T("HackerRank AI-Era","AI interviewer / resume deep dive")] },
  "Rapid-fire review": { min_level: 1, topics: [] },
};
write("sprint.yaml", { intro: SPRINT_INTRO, days: PLAN.map((day, di) => ({
  day: di + 1, title: day.d,
  blocks: day.b.map(([title, minutes, items], bi) => {
    const m = BLOCK_META[title]; if (!m) throw new Error("No sprint meta for " + title);
    return { id: `d${di + 1}-${slug(title)}`, title, minutes, min_level: m.min_level, topics: m.topics, order: bi + 1,
      items: items.map((text, ii) => ({ id: `d${di + 1}b${bi + 1}i${ii + 1}`, text, min_level: Math.max(m.min_level, (m.item_levels || {})[ii] || 1) })) };
  }),
})) });

// ---------- HackerRank AI-assisted interview module ----------
write("hackerrank.yaml", {
  title: "HackerRank AI-assisted interviews", min_level: 1,
  review_every_days: 90, last_reviewed: null,
  disclaimer: HR_DISCLAIMER,
  sections: HR.map(([title, body], i) => ({ id: slug(title), title, body, order: i + 1 })),
  related_topics: [...topicIndex.entries()].filter(([k]) => k.startsWith("HackerRank AI-Era|")).map(([, id]) => id),
});

// ---------- gamification (data-driven; evaluated on the server) ----------
const BADGE_RULES = [
  { type: "topics_done", gte: 1 }, { type: "streak_days", gte: 3 }, { type: "streak_days", gte: 7 },
  { type: "topics_done", gte: 10 }, { type: "topics_done", gte: 25 }, { type: "topics_done", gte: 50 },
  { type: "study_minutes", gte: 600 }, { type: "study_minutes", gte: 3000 },
  { type: "notes_count", gte: 5 }, { type: "revisions_count", gte: 5 },
  { type: "pareto_complete", scope: "any_held_level" },
  { type: "session_start_local_hour", from: 22, to: 4 }, { type: "session_start_local_hour", from: 5, to: 8 },
];
write("gamification.yaml", {
  xp: {
    topic_done:   { points: 30, idempotency_key: "topic_done:{topic_id}", note: "Once per topic, ever. Un-marking and re-marking done gives no extra XP." },
    revision:     { points: 10, idempotency_key: "revision:{topic_id}:{cycle}", only_when_due: true },
    note:         { points: 5,  idempotency_key: "note:{topic_id}", min_chars: 20 },
    attachment:   { points: 5,  idempotency_key: "attachment:{topic_id}" },
    study_minute: { points: 1,  idempotency_key: "session:{session_id}", min_session_minutes: 1, max_session_minutes: 240 },
  },
  levels: { formula: "min(max_level, floor(sqrt(xp / divisor)) + 1)", divisor: 40, max_level: 7,
    titles: TITLES.map((title, i) => ({ level: i + 1, title, min_xp: 40 * i * i })) },
  streak: { day_boundary: "profile_timezone", counts_as_activity: ["topic_done", "revision", "note", "attachment", "study_session"], today_optional: true },
  revision: { due_after_days: 5, overdue_after_days: 7, clock_starts: "max(done_at, last_revised_at)" },
  badges: BADGES.map(([icon, name], i) => ({ id: slug(name), name, icon, rule: BADGE_RULES[i], order: i + 1 })),
});

// ---------- encouragement messages ----------
write("messages.yaml", {
  tone: "Warm, specific, never guilt-inducing. No shaming for missed days or broken streaks.",
  time_of_day: [{ before_hour: 12, text: "Good morning" }, { before_hour: 18, text: "Good afternoon" }, { before_hour: 24, text: "Good evening" }],
  greeting: {
    headline: "{time_of_day}{name_suffix}! 👋",
    streak_active: "You’re on a {streak}-day streak. Let’s keep it going.",
    streak_none: "Today is a great day to start a streak.",
    revisions_due_one: "🔁 1 topic is due for revision (5–7 day rule). A quick review locks it in.",
    revisions_due_many: "🔁 {count} topics are due for revision (5–7 day rule). A quick review locks them in.",
    next_topic: "Suggested next: {topic}. One focused hour is plenty.",
    all_touched: "You’ve touched every topic, so now it’s all about revision and mock practice.",
    footer: "You’re preparing as a {level_name}. You’ve got this.",
  },
  topic_done_cheers: CH,
  closing: { summary_with_minutes: "You studied for {minutes} min this time.", summary_no_minutes: "Every visit counts.",
    totals: "Total: {topics_done} topics done, {hours} h studied.", farewells: BYE },
  toasts: {
    session_started: "Session started. Let’s make it count!", session_saved: "Saved {minutes} min. Great focus!", session_paused: "Session paused",
    revised: "Revised, nicely done", note_saved: "Note saved", attachment_added: "Attachment added",
    badge_unlocked: "{icon} Badge unlocked: {name}", level_up: "Level up! {title}", xp_gain: "+{points} XP",
  },
});

// ---------- app settings / defaults ----------
write("settings.yaml", {
  progress: { default_hours_per_topic: DASHBOARD_DEFAULTS.hours_per_topic, default_hours_per_day: DASHBOARD_DEFAULTS.hours_per_day,
    in_progress_weight: DASHBOARD_DEFAULTS.in_progress_weight, subtopics_drive_status: true },
  resources: { kinds: RESOURCE_KINDS, max_excerpt_chars: 20000 },
  uploads: { // sized for the Supabase free tier (1 GB storage per project)
    allowed_types: ["image/jpeg", "image/png", "image/webp", "image/heic", "application/pdf"],
    max_image_bytes: 5242880, client_compress_images_to_px: 1600, max_pdf_bytes: 10485760,
    per_user_quota_bytes: 26214400, signed_url_ttl_seconds: 3600, thumbnails: "client-side at upload (no paid image transforms)" },
  summary: { engine: "extractive", max_points: 4, min_sentence_chars: 25 },
});

console.log(`Built content/ : ${domains.length} domains, ${topicIndex.size} topics, ${CARDS.length} cards, ${DES.length} designs, ${PLAN.reduce((a, d) => a + d.b.length, 0)} sprint blocks, ${BADGES.length} badges.`);
